const LanguageContext = createContext(null);

export function PreferencesProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    const stored = localStorage.getItem("factlens_language");
    return ["en", "te", "hi"].includes(stored) ? stored : "en";
  });
  const [simpleMode, setSimpleMode] = useState(() => localStorage.getItem("factlens_simple_mode") === "true");

  useEffect(() => {
    document.documentElement.lang = language === "te" ? "te" : language === "hi" ? "hi" : "en";
  }, [language]);

  const t = useCallback((key) => translations[language]?.[key] || translations.en[key] || key, [language]);
  const value = useMemo(() => ({
    language,
    setLanguage: (next) => {
      localStorage.setItem("factlens_language", next);
      setLanguage(next);
    },
    simpleMode,
    setSimpleMode: (next) => {
      localStorage.setItem("factlens_simple_mode", String(next));
      setSimpleMode(next);
    },
    t,
    locale: language === "te" ? "te-IN" : language === "hi" ? "hi-IN" : "en-US",
    speechLocale: language === "te" ? "te-IN" : language === "hi" ? "hi-IN" : "en-US",
  }), [language, simpleMode, t]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function usePreferences() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("usePreferences must be used within PreferencesProvider");
  return context;
}

export function translateMessage(message, t) {
  if (typeof message !== "string" || !message) return "";
  const httpStatusPrefix = "The article server returned HTTP ";
  if (message.startsWith(httpStatusPrefix)) {
    return `${t("The article server returned HTTP")} ${message.slice(httpStatusPrefix.length)}`;
  }
  return t(message);
}
